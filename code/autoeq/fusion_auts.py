#!/usr/bin/env python3
"""Fusion ring automorphisms of C(g,k) from the Kac-Walton fusion rules, independently of the
F-symbol data, and their action on dimensions, twists and the S-matrix.

usage: fusion_auts.py TYPE LEVEL        e.g. F4 4, B6 2, G2 4

* fusion rules: ../f4/rootsys.py (Kac-Walton), checked associative;
* automorphisms: all permutations pi of the simple objects with N_{pi a, pi b}^{pi c} = N_{ab}^c
  (backtracking; pi preserves Frobenius-Perron dimensions, used only to prune, then rechecked);
* twists theta_X = exp(2 pi i h_X), h_X exact; for every pi: the set of a in (Z/2m(k+h))^* with
  theta_{pi X} = theta_X^a for all X (a = -1: pi inverts the twists);
* S-matrix (Kac-Peterson, numerically, 1e-10): S_{pi X, pi Y} = S_{X, Y}?
"""
import sys, os, math, cmath, itertools
from fractions import Fraction as Fr
import numpy as np
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "f4"))
from rootsys import RootSystem

typ, k = sys.argv[1], int(sys.argv[2])
R = RootSystem(typ)
kap = k + R.hdual
order = 2 * R.m * kap
W = R.alcove(k)
n = len(W)
lab = lambda w: "".join(map(str, w))
N = {}
for a in W:
    for b in W:
        for c, m in R.tensor(a, b, k).items():
            N[(a, b, c)] = m
Nm = {a: np.array([[N.get((a, b, c), 0) for c in W] for b in W]) for a in W}
for a, b in itertools.product(W, W):
    assert (Nm[a] @ Nm[b] == sum(N.get((a, b, c), 0) * Nm[c] for c in W)).all()


def qdim(lam):
    v = 1.0
    for al in R.positive_roots:
        v *= math.sin(math.pi * R.ip(tuple(l + 1 for l in lam), al) / (R.m * kap)) / math.sin(math.pi * R.ip(R.rho, al) / (R.m * kap))
    return v


d = {w: qdim(w) for w in W}
h = {w: R.h(w, k) for w in W}
print(f"C({typ},{k}): rank {n}, twists in mu_{order}")
unit = W[0]
inv = [w for w in W if abs(d[w] - 1) < 1e-9]
print("invertible objects:", [lab(w) for w in inv])
# simple products of non-unit simples (used in the braiding classification of the paper)
simp = [(lab(a), lab(b)) for a in W for b in W if a != unit and b != unit and sum(N.get((a, b, c), 0) for c in W) == 1]
print("pairs (X, Y), X, Y != 1, with X (x) Y simple:", simp)
# universal grading: the adjoint subcategory (generated by summands of X X*) is everything?
dual = {a: next(b for b in W if N.get((a, b, unit))) for a in W}
adj = {unit}
fr = [unit]
gens = {c for a in W for c in W if N.get((a, dual[a], c))}
while True:
    new = {c for x in adj for g in gens for c in W if N.get((x, g, c))} - adj
    if not new:
        break
    adj |= new
print(f"adjoint subcategory has {len(adj)} of {n} simples (universal grading group trivial: {len(adj) == n})")

# automorphisms
cls = {}
for w in W:
    key = round(d[w], 8)
    cls.setdefault(key, []).append(w)
others = W[1:]
auts = []


def ok(pi):
    dom = list(pi)
    return all(N.get((x, y, z), 0) == N.get((pi[x], pi[y], pi[z]), 0) for x in dom for y in dom for z in dom)


def rec(pi):
    if not ok(pi):
        return
    if len(pi) == n:
        auts.append(dict(pi)); return
    x = others[len(pi) - 1]
    for y in cls[round(d[x], 8)]:
        if y not in pi.values():
            pi[x] = y; rec(pi); del pi[x]


rec({unit: unit})
# recheck without the dimension pruning would be 16! ; instead: an automorphism preserves the FP
# dimension, the unique character positive on all simples, so the pruning loses nothing.
print(f"{len(auts)} fusion ring automorphisms")


def cyc_type(pi):
    seen, out = set(), []
    for x in W:
        if x in seen:
            continue
        c = [x]; seen.add(x); y = pi[x]
        while y != x:
            c.append(y); seen.add(y); y = pi[y]
        if len(c) > 1:
            out.append("(" + " ".join(lab(z) for z in c) + ")")
    return " ".join(out) or "id"


def compose(p, q):
    return {x: p[q[x]] for x in W}


# group structure
orders = []
for pi in auts:
    o, q = 1, pi
    while any(q[x] != x for x in W):
        q = compose(pi, q); o += 1
    orders.append(o)
print("element orders:", sorted(orders))

# S-matrix, Kac-Peterson, numerically
rho = R.rho
