"""Quantum group U_q(g) modules over F_p at a root of unity.

Conventions (Jantzen, Lectures on quantum groups): generators E_i, F_i, K_i with
  K_i E_j K_i^-1 = q^{(alpha_i, alpha_j)} E_j,  [E_i, F_j] = delta_ij (K_i - K_i^-1)/(q_i - q_i^-1),
  q_i = q^{d_i},  Delta(E_i) = E_i (x) 1 + K_i (x) E_i,  Delta(F_i) = F_i (x) K_i^-1 + 1 (x) F_i.
The form is normalised with short roots of length 2 (rootsys.py), so K_i acts on weight mu by
q^{d_i mu_i}.  q is a primitive root of unity of order 2 m (k + h^vee) in F_p.

A simple module L(lambda) (lambda restricted, so L(lambda) is generated by the plain F_i) is
built weight space by weight space from the top: the candidates for a basis of L_nu are the
vectors F_j b, b a basis vector of L_{nu + alpha_j}; a combination of candidates is zero in L
iff it is killed by every E_i, and the basis is the set of pivot candidates.  Every basis vector
is therefore F_j applied to a basis vector one step up, which defines U^- module maps out of L.

Highest weight vectors in M (x) V (V small) are computed from their component along the top
vector of M ("tau", injective): the lower components are forced by E_i-equations.
"""
import numpy as np
from lin import Fp


def wadd(a, b, s=1):
    return tuple(x + s * y for x, y in zip(a, b))


class QG:
    def __init__(self, R, p, q, order):
        self.R, self.p, self.q, self.order = R, p, q, order
        self.F = Fp(p)
        assert pow(q, order, p) == 1 and all(pow(q, order // l, p) != 1 for l in _prime_factors(order))
        self.alpha = [R.alpha(j) for j in range(R.rank)]

    def qp(self, n):
        return pow(self.q, int(n) % self.order, self.p)

    def qint(self, n, d=1):
        p = self.p
        num = (self.qp(d * n) - self.qp(-d * n)) % p
        den = (self.qp(d) - self.qp(-d)) % p
        return num * pow(den, -1, p) % p

    def K(self, i, mu):
        return self.qp(self.R.d[i] * mu[i])


def _prime_factors(n):
    out, d = [], 2
    while d * d <= n:
        while n % d == 0:
            out.append(d)
            n //= d
        d += 1
    if n > 1:
        out.append(n)
    return sorted(set(out))


class Module:
    """Truncated (to a given depth below the top) simple module L(lam)."""

    def __init__(self, G, lam, maxdepth=None, check=True):
        R, F, p = G.R, G.F, G.p
        self.G, self.top = G, tuple(lam)
        r = R.rank
        al = G.alpha
        self.dim = {self.top: 1}
        self.E, self.Fm, self.cand = {}, {}, {self.top: []}
        self.depth = {self.top: 0}
        ch = R.character(lam) if check else None
        layer = [self.top]
        h = 0
        while layer and (maxdepth is None or h < maxdepth):
            h += 1
            new = sorted({wadd(mu, al[j], -1) for mu in layer for j in range(r)})
            nxt = []
            for nu in new:
                srcs = [(j, wadd(nu, al[j])) for j in range(r) if wadd(nu, al[j]) in self.dim]
                cands = [(j, b) for j, s in srcs for b in range(self.dim[s])]
                blocks = []
                for i in range(r):
                    up = wadd(nu, al[i])
                    if up not in self.dim:
                        continue
                    M = np.zeros((self.dim[up], len(cands)), dtype=np.int64)
                    col = 0
                    for j, src in srcs:
                        ns = self.dim[src]
                        part = np.zeros((self.dim[up], ns), dtype=np.int64)
                        su = wadd(src, al[i])
                        if su in self.dim and (i, src) in self.E and (j, su) in self.Fm:
                            part = F.mm(self.Fm[(j, su)], self.E[(i, src)])
                        if i == j:
                            part = (part + G.qint(src[i], R.d[i]) * np.eye(ns, dtype=np.int64)) % p
                        M[:, col:col + ns] = part
                        col += ns
                    blocks.append((i, up, M))
                C = np.concatenate([b[2] for b in blocks], axis=0)
                Rr, piv = F.rref(C)
                d = len(piv)
                if check:
                    assert d == ch.get(nu, 0), ("dimension mismatch", lam, nu, d, ch.get(nu, 0))
                if d == 0:
                    continue
                self.dim[nu] = d
                self.depth[nu] = h
                nxt.append(nu)
                for i, up, M in blocks:
                    self.E[(i, nu)] = M[:, piv]
                col = 0
                for j, src in srcs:
                    ns = self.dim[src]
                    self.Fm[(j, src)] = Rr[:, col:col + ns].copy()
                    col += ns
                self.cand[nu] = [cands[c] for c in piv]
            layer = nxt
        self.maxdepth = h
        self.complete = not layer
        self._linv = {}

    def weights(self):
        return self.dim.keys()

    def Emat(self, i, mu):
        """E_i : L_mu -> L_{mu + alpha_i} (zero matrix if absent)."""
        up = wadd(mu, self.G.alpha[i])
        if up not in self.dim or mu not in self.dim:
            return np.zeros((self.dim.get(up, 0), self.dim.get(mu, 0)), dtype=np.int64)
        return self.E[(i, mu)]

    def Fmat(self, j, mu):
        """F_j : L_mu -> L_{mu - alpha_j}."""
        dn = wadd(mu, self.G.alpha[j], -1)
        if dn not in self.dim or mu not in self.dim:
            return np.zeros((self.dim.get(dn, 0), self.dim.get(mu, 0)), dtype=np.int64)
        return self.Fm[(j, mu)]

    def stackedE(self, mu):
        return np.concatenate([self.Emat(i, mu) for i in range(self.G.R.rank)], axis=0)

    def linv(self, mu):
        if mu not in self._linv:
            self._linv[mu] = self.G.F.left_inverse(self.stackedE(mu))
        return self._linv[mu]


def uminus_map(M, top_image, applyF, weights):
    """U^- module map out of M given the image of the top vector.
    applyF(j, vec) applies F_j in the target to a column vector (or matrix of columns).
    Returns dict weight -> matrix whose columns are images of the basis of M_weight."""
    memo = {M.top: np.asarray(top_image, dtype=np.int64).reshape(-1, 1)}

    def get(mu):
        if mu in memo:
            return memo[mu]
        cols = []
        for (j, b) in M.cand[mu]:
            src = wadd(mu, M.G.alpha[j])
            cols.append(applyF(j, src, get(src)[:, b:b + 1]))
        memo[mu] = np.concatenate(cols, axis=1)
        return memo[mu]
    return {mu: get(mu) for mu in weights}


class TensorV:
    """Highest weight vectors in M (x) V for a small module V (complete)."""

    def __init__(self, G, V):
        self.G, self.V = G, V
        self.vw = sorted(V.dim, key=lambda w: (-V.depth[w], w))
        self.off = {}
        o = 0
        for w in sorted(V.dim, key=lambda w: (V.depth[w], w)):
            self.off[w] = o
            o += V.dim[w]
        self.n = o

    def hw(self, M, C):
        """Basis of highest weight vectors of weight C in M (x) V.
        Returns (list of dict mu -> array (dim M_mu, dim V_{C-mu})), tau matrix (n x k)):
        tau columns are the M-top components, embedded in V (length n)."""
        G, V, F, p, R = self.G, self.V, self.G.F, self.G.p, self.G.R
        r = R.rank
        top = M.top
        wtop = wadd(C, top, -1)
        if wtop not in V.dim:
            return [], np.zeros((self.n, 0), dtype=np.int64)
        npar = V.dim[wtop]
        # weights of M involved
        mus = [wadd(C, w, -1) for w in V.dim]
        mus = [mu for mu in mus if mu in M.dim]
        missing = [mu for mu in [wadd(C, w, -1) for w in V.dim] if mu not in M.dim and _inside(M, mu)]
        assert not missing, ("module truncated too early", M.top, C, missing[:3])
        mus.sort(key=lambda mu: M.depth[mu])
        v = {}
        for mu in mus:
            w = wadd(C, mu, -1)
            if mu == top:
                v[mu] = np.eye(npar, dtype=np.int64).reshape(1, npar, npar)
                continue
            rhs = []
            for i in range(r):
                up = wadd(mu, G.alpha[i])
                if up not in M.dim:
                    continue
                blk = np.zeros((M.dim[up], V.dim[w], npar), dtype=np.int64)
                if up in v:
                    wu = wadd(C, up, -1)
                    EV = V.Emat(i, wu)                       # V_{wu} -> V_{w}
                    if EV.shape[0]:
                        kk = G.K(i, up)
                        t = _cmid(F, EV, v[up])
                        blk = (-kk * t) % p
                rhs.append(blk)
            rhs = np.concatenate(rhs, axis=0)
            L = M.linv(mu)
            sol = F.mm(L, rhs.reshape(rhs.shape[0], -1)).reshape(M.dim[mu], V.dim[w], npar)
            v[mu] = sol
        # constraints: Delta(E_i) v = 0 everywhere
        cons = []
        for i in range(r):
            outs = {}
            for mu, x in v.items():
                w = wadd(C, mu, -1)
                up = wadd(mu, G.alpha[i])
                if up in M.dim:
                    t = _cleft(F, M.Emat(i, mu), x)
                    key = (up, w)
                    outs[key] = (outs.get(key, 0) + t) % p
                elif _inside(M, up) and wadd(w, (0,) * r) in V.dim:
                    raise AssertionError("truncation")
                wu = wadd(w, G.alpha[i])
                if wu in V.dim:
                    EV = V.Emat(i, w)
                    t = (G.K(i, mu) * _cmid(F, EV, x)) % p
                    key = (mu, wu)
                    outs[key] = (outs.get(key, 0) + t) % p
            for key, t in outs.items():
                cons.append(np.asarray(t).reshape(-1, npar))
        Cm = np.concatenate(cons, axis=0) if cons else np.zeros((0, npar), dtype=np.int64)
        N = F.nullspace(Cm % p)
        vecs = []
        for k in range(N.shape[1]):
            c = N[:, k]
            vecs.append({mu: (x @ c) % p if x.shape[2] else x[:, :, 0] for mu, x in v.items()})
        tau = np.zeros((self.n, N.shape[1]), dtype=np.int64)
        tau[self.off[wtop]:self.off[wtop] + npar, :] = N
        return vecs, tau

    def applyF_V(self, j, src_w, cols):
        """F_j on V restricted to weight src_w (cols: column vectors in V_src)."""
        return self.G.F.mm(self.V.Fmat(j, src_w), cols)


def _cleft(F, A, x):
    m, b, c = x.shape
    return F.mm(A, x.reshape(m, b * c)).reshape(A.shape[0], b, c)


def _cmid(F, A, x):
    m, b, c = x.shape
    y = F.mm(A, x.transpose(1, 0, 2).reshape(b, m * c)).reshape(A.shape[0], m, c)
    return y.transpose(1, 0, 2).copy()


def _inside(M, mu):
    """True if mu should be a weight of the (untruncated) module but lies below the truncation."""
    if mu in M.dim or M.complete:
        return False
    h = sum(M.G.R.root_coords(wadd(M.top, mu, -1)))
    return h >= M.maxdepth and all(c >= 0 for c in M.G.R.root_coords(wadd(M.top, mu, -1))) \
        and M.G.R.character(M.top).get(mu, 0) > 0
